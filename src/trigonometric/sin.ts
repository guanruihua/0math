/**
 * @title sin
 * @description 正弦
 * @param {number} value
 * @returns {number}
 */
export function sin(value: number): number {
  return Math.sin(value)
}

/**
 * @title asin
 * @description 反正弦
 * @param {number} value
 * @returns {number}
 */
export function asin(value: number): number {
  return Math.asin(value)
}

/**
 * @title asin
 * @description 反双曲正弦
 * @param {number} value
 * @returns {number}
 */
export function asinh(value: number): number {
  return Math.asinh(value)
}
